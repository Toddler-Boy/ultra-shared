#include <algorithm>

#include "Easings.h"

//-----------------------------------------------------------------------------

float easing::smoothstep ( float t )
{
	t = std::clamp ( t, 0.0f, 1.0f );

	return t * t * ( 3.0f - 2.0f * t );
}
//-----------------------------------------------------------------------------

float easing::smootherstep ( float t )
{
	t = std::clamp ( t, 0.0f, 1.0f );

	return t * t * t * ( t * ( 6.0f * t - 15.0f ) + 10.0f );
}
//-----------------------------------------------------------------------------
